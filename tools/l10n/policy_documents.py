"""Read the website's two policy articles into the offline SwiftUI document and its catalog keys."""

import json
from html.parser import HTMLParser
from pathlib import Path
from urllib.parse import urlparse
from xml.etree.ElementTree import Element, SubElement


class ArticleParser(HTMLParser):
    def __init__(self):
        super().__init__()
        self.article = None
        self.stack = []

    def handle_starttag(self, tag, attrs):
        if tag == "article":
            if self.article is not None:
                raise ValueError("Expected exactly one policy article")
            self.article = Element(tag, dict(attrs))
            self.stack.append(self.article)
        elif self.stack:
            self.stack.append(SubElement(self.stack[-1], tag, dict(attrs)))

    def handle_endtag(self, tag):
        if self.stack and self.stack.pop().tag != tag:
            raise ValueError(f"Unbalanced element in policy article: {tag}")

    def handle_data(self, data):
        if self.stack:
            self.stack[-1].text = (self.stack[-1].text or "") + data


def policy_documents(web_root):
    swift = ["// Generated by tools/l10n/build_catalog.py from privacy.html and terms.html.",
             "import Foundation", "", "extension PolicyDocument {"]
    web_keys = {}

    def string(element):
        text = (element.text or "").strip()
        if not text:
            raise ValueError(f"Empty policy element: {element.tag}")
        literal = json.dumps(text, ensure_ascii=False)
        if "data-site-text" in element.attrib:
            key = element.attrib["data-site-text"]
            if not key:
                raise ValueError(f"Missing web translation key for {text!r}")
            if text in web_keys and web_keys[text] != key:
                raise ValueError(f"Ambiguous English policy text: {text!r}")
            web_keys[text] = key
            return f'String(localized: {literal}, table: "Policies")'
        return literal

    for name in ("privacy", "terms"):
        parser = ArticleParser()
        parser.feed((Path(web_root) / f"{name}.html").read_text(encoding="utf-8"))
        parser.close()
        if parser.stack:
            raise ValueError(f"Unclosed element in {name}.html")
        article = parser.article
        if article is None or article.find("h1") is None:
            raise ValueError(f"{name}.html has no article title")
        title = string(article.find("h1"))
        swift += [f"    static var {name}: Self {{", f"        Self(title: {title}, blocks: ["]
        for element in article.iter():
            if element.tag in ("article", "section", "h1"):
                continue
            if element.tag == "a":
                url = element.attrib["href"]
                if urlparse(url).scheme not in ("https", "mailto"):
                    raise ValueError(f"Unsupported policy link: {url}")
                swift.append(f"            .link({string(element)}, URL(string: {json.dumps(url)})!),")
                continue
            if element.tag == "p" and len(element):
                if (element.text or "").strip() or any(child.tag != "a" for child in element):
                    raise ValueError("Expected a separate link paragraph in the policy article")
                continue
            if element.tag == "h2":
                kind = "heading"
            elif element.tag == "p":
                if "policy-status" in element.attrib.get("class", "").split():
                    kind = "status"
                elif element in list(article):
                    kind = "lead"
                else:
                    kind = "paragraph"
            else:
                raise ValueError(f"Unsupported element in the policy article: {element.tag}")
            swift.append(f"            .{kind}({string(element)}),")
        swift += ["        ])", "    }", ""]
    swift[-1] = "}"
    return "\n".join(swift) + "\n", web_keys
